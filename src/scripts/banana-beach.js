  // untouched — which is the standalone-first law, not an optimisation.
  function sandyOwnsBall() {
    return !bayRoom.live || peers.size === 0 || inCourt(pos.x, pos.y);
  }
  function drawPeer(p, force) {
    // same redraw key as drawMe(): frame AND depth, because a peer wading out
    // changes tint without changing frame — key on frame alone and the tint
    // freezes at whatever depth they were at when the frame last ticked.
    const f = p.sit ? (p.fishFrame != null ? p.fishFrame : SIT_FRAME) : frameNow();
    const q = Math.round(subAt(p.x, p.y) * 40);
    const key = f * 64 + q;
    if (!force && key === p.key) return;
    p.key = key;
    const sub = q / 40;
    drawComposite(p.ctx, CV, f, {
      ...p.outfit, top: '', bottom: '', bg: 'transparent', captions: false, effect: 'none',
    });
    applySubmerge(p.ctx, sub, f * 0.9);
    p.el.classList.toggle('is-wet', q > 0);
  }
  function placePeer(p) {
    p.el.style.left = pct(p.x, W);
    p.el.style.top = pct(p.y, H);
    depth(p.el, p.y);          // sorts against the net and the palms like you
  }
  // ---- 🎣 A PEER'S FISHING ROD --------------------------------------------
  // Needs NO new network state: a fishing seat is a fixed spot and a fishing
  // banana sits exactly ON it, so a sitting peer whose position matches a dock
  // chair IS fishing. We then draw the SAME static rod + line + float the local
  // rod uses (startFishing's geometry, factored here) — no bite, no reel, no
  // catch, just the rod, which is all Trym asked to see. The float keeps its
  // idle bob; nothing here tracks the other player's actual catch.
  function makePeerRod(spot) {
    const bx = spot.bob.x, by = spot.bob.y;
    const dir = bx >= spot.seat.x ? 1 : -1;
    const hx = spot.seat.x + dir * 7, hy = spot.seat.y - 25;
    const tipX = hx + dir * 40, tipY = hy - 34;
    const zTop = 100 + spot.seat.y + 6;
    const rod = seg('bh-fishrod', hx, hy, Math.hypot(tipX - hx, tipY - hy),
      Math.atan2(tipY - hy, tipX - hx) * 180 / Math.PI, zTop);
    const lineAng = Math.atan2(by - tipY, bx - tipX) * 180 / Math.PI;
    const line = seg('bh-fishline', tipX, tipY, Math.hypot(bx - tipX, by - tipY), lineAng, zTop);
    line.style.setProperty('--ang', lineAng.toFixed(2) + 'deg');
    const bob = document.createElement('div');
    bob.className = 'bh-bob';
    bob.style.left = pct(bx, W); bob.style.top = pct(by, H); bob.style.zIndex = String(zTop + 1);
    world.appendChild(bob);
    return [rod, line, bob];
  }
  const peerFishSpot = (p) => (p.sit
    ? FISH_SPOTS.find((s) => s.fishing && Math.hypot(s.seat.x - p.x, s.seat.y - p.y) < 24)
    : null) || null;
  function updatePeerRod(p) {
    const spot = peerFishSpot(p);
    if (spot && !p.rod) {
      p.rod = makePeerRod(spot);
      p.fishFrame = spot.sitFrame;       // face their own water, like the seat does
      drawPeer(p, true);
    } else if (!spot && p.rod) {
      clearPeerRod(p);
      p.fishFrame = null;
      drawPeer(p, true);
    }
  }
  function clearPeerRod(p) {
    if (p.rod) { p.rod.forEach((e) => e.remove()); p.rod = null; }
  }
  function addPeer(d) {
    if (!d || d.id === myBayId || peers.has(d.id)) return;
    const el = document.createElement('div');
    el.className = 'bh-peer';
    const cv = document.createElement('canvas');
    cv.width = CV; cv.height = CV;
    el.appendChild(cv);
    if (d.name) { const tag = document.createElement('span'); tag.textContent = d.name; el.appendChild(tag); }
    world.appendChild(el);
    const p = {
      el, ctx: cv.getContext('2d'), outfit: d.outfit || {}, name: d.name || '',
      x: d.x ?? 898, y: d.y ?? 742, sit: !!d.sit, key: -1,
    };
    el.classList.toggle('is-sitting', p.sit);
    peers.set(d.id, p);
    placePeer(p);
    drawPeer(p, true);
    updatePeerRod(p);          // joined already fishing? show the rod
    refreshCrowd();
    recountCourt();
  }
  // ---- 🏐 THE SHARED BALLS ------------------------------------------------
  // ⚠️ ONE PACKET PER HIT. Both balls are pure physics from a known state, so
  // a snapshot at the moment of contact is all anyone needs: every client
  // integrates the same constants from the same numbers and draws the same
  // arc. A rally costs about one message per bounce instead of sixty a
  // second, and the next hit resyncs whatever drift crept in.
  // ⚠️ Sub-pixel state is deliberately NOT sent — the room rounds everything.
  // At these speeds a 1px seed difference is invisible within a single flight,
  // and rounding halves the packet.
  function sendBall(which) {
    if (!bayRoom.live) return;
    const b = which === 'w' ? WBALL : ball;
    bayRoom.send({ t: 'ball', b: which, x: b.x, y: b.y, z: b.z, vx: b.vx, vy: b.vy, vz: b.vz });
  }
  function applyBall(m) {
    const b = m.b === 'w' ? WBALL : ball;
    b.x = m.x; b.y = m.y; b.z = m.z;
    b.vx = m.vx; b.vy = m.vy; b.vz = m.vz;
    // the volleyball's rally counter belongs to whoever is playing it, so a
    // remote hit must not reset YOUR rest timer into a dead rally
    if (m.b === 'w') float(WBALL.x, WBALL.y - 20, 'splash!');
  }
  const bayRoom = presenceRoom({
    url: BEACH_WS,
    hi: () => ({ outfit: myBayOutfit(), x: pos.x, y: pos.y, sit: !!seated, name: bayName }),
    onMessage: (m) => {
      if (m.t === 'roster') { myBayId = m.you; (m.all || []).forEach(addPeer); refreshCrowd(); }
      else if (m.t === 'join') addPeer(m.p);
      else if (m.t === 'ball') applyBall(m);
      else if (m.t === 'move') {
        const p = peers.get(m.id);
        if (p) {
          p.x = m.x; p.y = m.y; p.sit = !!m.sit;
          p.el.classList.toggle('is-sitting', p.sit);
          placePeer(p);
          updatePeerRod(p);        // sat down to fish, or got up and walked off
          recountCourt();          // they may have just walked onto the court
        }
      } else if (m.t === 'outfit') {
        const p = peers.get(m.id);
        if (p) { p.outfit = m.outfit || {}; drawPeer(p, true); }
      } else if (m.t === 'leave') {
        const p = peers.get(m.id);
        if (p) {
          // the puff anchors at the BODY, not the feet — poofInto takes
          // percent, and a peer's y is its feet line
          poofInto(world, 'bh-poof', p.x / W * 100, (p.y - 26) / H * 100);
          clearPeerRod(p);         // don't strand their rod on the dock
          p.el.remove();
          peers.delete(m.id);
          refreshCrowd();
          recountCourt();          // the court may have just emptied out
        }
      }
    },
    onDown: () => {
      peers.forEach((p) => { clearPeerRod(p); p.el.remove(); }); peers.clear();
      refreshCrowd(); recountCourt();   // socket died → Sandy comes back
    },
  });
  function baySendMove(now) {
    if (!bayRoom.live || now - baySendAt < 150) return;
    const sit = !!seated;
    if (Math.abs(pos.x - lastSent.x) < 1 && Math.abs(pos.y - lastSent.y) < 1 && sit === lastSent.sit) return;
    baySendAt = now;
    lastSent.x = pos.x; lastSent.y = pos.y; lastSent.sit = sit;
    bayRoom.send({ t: 'move', x: pos.x, y: pos.y, sit });
  }

  // ---- 🏖 THE BEACH-DAY CARD ----------------------------------------------
  // The bay's answer to the rave's side panel: who's here, your day's numbers,
  // and a shareable postcard. Everything it shows already exists — shells, fish
  // and tickets are pass stats, the roster is the peers we already track, the
  // timer is this session. Refreshed on a 1s tick (cheap: a handful of nodes),
  // which doubles as the clock and picks up roster/stat changes without
  // threading a call through every handler.
  const beachStart = Date.now();
  function beachTime() {
    const t = Math.max(0, Math.floor((Date.now() - beachStart) / 1000));
    const h = Math.floor(t / 3600), m = Math.floor((t % 3600) / 60), s = t % 60;
    return h ? h + 'h ' + m + 'm' : m ? m + 'm ' + s + 's' : s + 's';
  }
  const esc = (s) => String(s).replace(/[&<>"]/g, (c) =>
    ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
  const rosterEl = document.getElementById('bhRoster');
  const dayStatsEl = document.getElementById('bhDayStats');
  function refreshSide() {
    if (dayStatsEl) {
      dayStatsEl.innerHTML =
        '<span class="bh-daystats__time">⏱ <b>' + beachTime() + '</b> on the beach</span>'
        + '<span>🐚 <b>' + haveCount() + '</b>/' + SHELL_IDS.length + ' shells</span>'
        + '<span>🐟 <b>' + fishSpecies() + '</b>/' + FISH.length + ' fish</span>'
        + '<span>🎟 <b>' + ticketBal() + '</b> tickets</span>'
        + '<span>🏐 <b>' + bestRally + '</b> best rally</span>';
    }
    if (rosterEl) {
      const me = '<li class="is-you"><span>' + esc(bayName || 'you')
        + '</span><span class="bh-roster__tag">YOU</span></li>';
      const others = [...peers.values()]
        .map((p) => '<li><span>' + esc(p.name || 'a banana') + '</span></li>').join('');
      rosterEl.innerHTML = me + others;
    }
  }
  refreshSide();
  setInterval(() => { if (!document.hidden) refreshSide(); }, 1000);

  // ---- 📸 SHARE MY BEACH DAY: a 1080×1080 postcard rendered on the spot ----
  // Same idea as the rave's share card — YOUR banana big and tilted, today's
  // numbers beside it — but a beach postcard: a teal sea band up top, warm sand
  // below, a low sun. Composed here so it captures the outfit and stats live.
  async function shareBeach() {
    try { await document.fonts.ready; } catch (e) {}
    const S = 1080;
    const cv = document.createElement('canvas');
    cv.width = cv.height = S;
    const c = cv.getContext('2d');
    // sand ground (warm), a teal sea band across the top, a foam seam
    const sand = c.createLinearGradient(0, S * 0.32, 0, S);
    sand.addColorStop(0, '#f2d79b');
    sand.addColorStop(1, '#e6be7c');
    c.fillStyle = sand; c.fillRect(0, 0, S, S);
    const sea = c.createLinearGradient(0, 0, 0, S * 0.34);
    sea.addColorStop(0, '#2f8fa8');
    sea.addColorStop(1, '#54b6c8');
    c.fillStyle = sea; c.fillRect(0, 0, S, S * 0.34);
    c.fillStyle = 'rgba(255,255,255,0.5)';
    for (let x = 0; x < S; x += 20) c.fillRect(x, Math.round(S * 0.34) - 6 + (x % 40 ? 0 : 3), 14, 6);
    // ☀️ SUNBEAMS — Trym liked the rave card's spotlight stripes; here they
    // RADIATE from the sun as god-rays. Each is a thin wedge with its apex at
    // the sun that widens across the card, filled with a yellow gradient that
    // fades to nothing — transparent stripes beaming down over the water and
    // sand. Drawn UNDER the sun disc (its apex is hidden by the disc) and under
    // everything else, so they're atmosphere, not clutter.
    const SUNX = 880, SUNY = 150;
    c.save();
    c.translate(SUNX, SUNY);
    for (let i = 0; i < 8; i++) {
      c.save();
      c.rotate((98 + i * 11.5) * Math.PI / 180);   // fan from straight-down to the left
      const len = 1500, w0 = 6, w1 = 74 + (i % 2) * 34;   // uneven widths read as real light
      const g = c.createLinearGradient(0, 0, len, 0);
      g.addColorStop(0, 'rgba(255,236,150,0.16)');
      g.addColorStop(1, 'rgba(255,236,150,0)');
      c.fillStyle = g;
      c.beginPath();
      c.moveTo(0, -w0); c.lineTo(len, -w1); c.lineTo(len, w1); c.lineTo(0, w0);
      c.closePath(); c.fill();
      c.restore();
    }
    c.restore();
    // the low sun, top-right, and its glow
    const sun = c.createRadialGradient(SUNX, SUNY, 20, SUNX, SUNY, 320);
    sun.addColorStop(0, 'rgba(255,236,150,0.9)');
    sun.addColorStop(1, 'rgba(255,236,150,0)');
    c.fillStyle = sun; c.fillRect(400, 0, S - 400, 500);
    c.fillStyle = '#ffe89a'; c.beginPath(); c.arc(SUNX, SUNY, 66, 0, Math.PI * 2); c.fill();
    // faint checker-free sand speckle so the ground isn't flat
    c.fillStyle = 'rgba(180,140,80,0.18)';
    for (let i = 0; i < 90; i++) c.fillRect(((i * 733) % S), 360 + ((i * 379) % (S - 400)), 6, 6);
    // your banana — hands-up frame, big, tilted, hugging the left edge
    const bcv = document.createElement('canvas');
    bcv.width = bcv.height = 1024;
    drawComposite(bcv.getContext('2d'), 1024, 2, {
      bg: 'transparent', captions: false, top: '', bottom: '',
      hat: ME_DRAW.hat, glasses: ME_DRAW.glasses, extras: ME_DRAW.extras || {}, effect: 'none',
    });
    // a soft contact shadow on the sand under him
    c.fillStyle = 'rgba(120,80,30,0.28)';
    c.beginPath(); c.ellipse(255, 940, 190, 42, 0, 0, Math.PI * 2); c.fill();
    c.save();
    c.imageSmoothingEnabled = false;
    c.translate(150, 640);
    c.rotate(-9 * Math.PI / 180);
    c.drawImage(bcv, -620, -620, 1240, 1240);
    c.restore();
    // type, right-aligned, the banana leans into it
    c.textAlign = 'right';
    c.fillStyle = '#3a2b18';
    c.font = '800 44px "Archivo Black", sans-serif';
    c.fillText('MY DAY AT', S - 60, 130);
    c.fillStyle = '#0f6f86';
    c.font = '800 82px "Archivo Black", sans-serif';
    c.fillText('BANANA BAY', S - 60, 220);
    c.shadowColor = 'rgba(0,0,0,0.35)'; c.shadowBlur = 14;
    c.fillStyle = '#e6712a';
    c.font = '800 42px "Archivo Black", sans-serif';
    c.fillText('SUNBATHED FOR ' + beachTime().toUpperCase(), S - 60, 292);
    c.shadowBlur = 0;
    const rows = [
      [haveCount() + '/' + SHELL_IDS.length, 'SHELLS'],
      [fishSpecies() + '/' + FISH.length, 'FISH'],
      [String(ticketBal()), ticketBal() === 1 ? 'TICKET' : 'TICKETS'],
      [String(bestRally), 'BEST RALLY'],
    ];
    let y = 400;
    for (const [n, label] of rows) {
      c.shadowColor = 'rgba(255,255,255,0.85)'; c.shadowBlur = 20;
      c.fillStyle = '#7a3d12';
      c.font = '800 96px "Archivo Black", sans-serif';
      c.textAlign = 'right';
      c.fillText(String(n), S - 470, y);
      c.shadowBlur = 8;
      c.fillStyle = '#3a2b18';
      c.font = '800 34px "Archivo Black", sans-serif';
      c.textAlign = 'left';
      c.fillText(label, S - 445, y - 8);
      c.textAlign = 'right';
      c.shadowBlur = 0;
      y += 132;
    }
    c.fillStyle = '#3a2b18';
    c.font = '700 30px "Archivo Black", sans-serif';
    c.fillText((bayName || 'a banana').toUpperCase(), S - 60, S - 116);
    c.fillStyle = '#0f6f86';
    c.font = '800 34px "Archivo Black", sans-serif';
    c.fillText('trymstene.com', S - 60, S - 62);
    track('beach_share_day');
    openBeachShare(cv);
  }
  const BEACH_SHARE_FILE = 'my-day-banana-bay-trymstene.com.png';
