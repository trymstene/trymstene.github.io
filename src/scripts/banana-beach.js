  // ---- 🏐🌊 THE WATER BALL: a TOY, not a sport ------------------------------
  // No z, no gravity, no shadow, no rally, no net. It floats, so the entire
  // physics is 2D drift plus thick drag. It reuses the volleyball's wall
  // reflect and its tap-or-fetch verb and NOTHING else — a floating ball that
  // borrowed GRAV and vz would be the volleyball with extra steps.
  const wballEl = document.getElementById('bhWBall');
  const wballSh = document.getElementById('bhWBallShadow');
  // ⚠️ IT HAS A HEIGHT NOW. Trym: "needs to bounce up from the water, like the
  // volleyball, now its sliding along the water." The first version was pure
  // 2D drift, which is what a ball nudged along a surface does — but a struck
  // beach ball leaves the surface. Same shape as the volleyball: z, vz, a
  // gravity, and a bounce that keeps most of the height. Water is a softer
  // floor than sand, so the restitution is lower than the volleyball's and the
  // ball settles after three or four hops instead of ringing on.
  const WBALL = { x: 900, y: 236, z: 0, vx: 0, vy: 0, vz: 0 };
  const WB_GRAV = 380, WB_HOP = 0.58;
  // ⚠️ BOUNCY, not soggy. Trym: "the water-ball must be more bouncy so that
  // one can bounce it a distance to eachother." The first pass had WB_DRAG
  // 0.30 — v is multiplied by pow(DRAG, dt), so 0.30 kills 70% of the speed
  // every second and the ball died about a banana-and-a-half away. 0.66 lets
  // a good shove carry ~500px, which is a real pass between two players.
  const WB_R = 22, WB_DRAG = 0.004, WB_WALL = 0.86, WB_PUSH = 330, WB_MAX = 520;
  const WB_SPLASH = 0.62;      // horizontal speed kept through each splash-down
  const WB_COOL = 240;
  // ⚠️ THE PEN IS IN WATER ROWS, NOT FEET ROWS. SWIM.ySea/yShore are `pos.y`
  // values, and a banana's feet draw 13.5px above pos.y — the ball has no
  // feet. Fenced by the painted shoreline instead: the last water row is 269,
  // so y1 = 269 − WB_R keeps the ball off the sand it would otherwise rest on.
  const PEN = { x0: SWIM.x0 + WB_R, x1: SWIM.x1 - WB_R,
                y0: SWIM.ySea - 13 + WB_R, y1: 269 - WB_R };
  let lastShove = 0, prevX = pos.x, prevY = pos.y;

  function wballStep(dt, now) {
    // contact at pos.y − 8, the volleyball's own convention (:546). An earlier
    // draft used the SCREEN-projected waterline drawn on the sprite, which
    // slides ~45px seaward as you submerge — you could stand on the ball and
    // not reach it.
    if (now - lastShove > WB_COOL
        && Math.hypot(pos.x - WBALL.x, (pos.y - 8) - WBALL.y) < WB_R + 34) {
      lastShove = now;
      const ax = WBALL.x - pos.x, ay = WBALL.y - (pos.y - 8);
      const al = Math.hypot(ax, ay) || 1;
      // mostly away from the banana, plus a splash of its own travel — so a
      // running shove goes further than a standing poke. The only "skill"
      // this toy needs.
      WBALL.vx = (ax / al) * WB_PUSH + (pos.x - prevX) / Math.max(dt, 0.001) * 0.25;
      WBALL.vy = (ay / al) * WB_PUSH + (pos.y - prevY) / Math.max(dt, 0.001) * 0.25;
      const s = Math.hypot(WBALL.vx, WBALL.vy);
      if (s > WB_MAX) { WBALL.vx *= WB_MAX / s; WBALL.vy *= WB_MAX / s; }
      WBALL.vz = 205;                       // it POPS — the hit lifts it out
      float(WBALL.x, WBALL.y - 20, 'splash!');
      sendBall('w');                        // 🌐 so it's the SAME ball out there
    }
    const prevZ = WBALL.z;                    // was it airborne last frame?
    WBALL.x += WBALL.vx * dt; WBALL.y += WBALL.vy * dt;
    WBALL.z += WBALL.vz * dt; WBALL.vz -= WB_GRAV * dt;
    if (WBALL.z <= 0) {
      WBALL.z = 0;
      // ⭐ EVERY SPLASH-DOWN EATS 38% OF THE RUN, and this — not the drag — is
      // what finally stopped it sliding around. The ball is AIRBORNE for
      // almost the whole bounce sequence, so a fierce water drag barely gets a
      // chance to touch it: it only applies in the instants the ball is on the
      // surface. Tuning that number three times (0.66 → 0.10 → 0.02) changed
      // almost nothing, because it was never the thing carrying the ball
      // across the bay. Hitting the water is. Four bounces now leave it with
      // ~15% of the speed it was thrown at.
      if (prevZ > 0) { WBALL.vx *= WB_SPLASH; WBALL.vy *= WB_SPLASH; }
      // the deadband stops it buzzing on the surface forever
      WBALL.vz = WBALL.vz < -60 ? -WBALL.vz * WB_HOP : 0;
    }
    // in the air it barely slows — the distance is bought up there, so a good
    // pass still carries. On the surface the water takes what the splash left.
    const damp = Math.pow(WBALL.z > 1 ? 0.94 : WB_DRAG, dt);
    WBALL.vx *= damp; WBALL.vy *= damp;
    if (WBALL.x < PEN.x0) { WBALL.x = PEN.x0; WBALL.vx = Math.abs(WBALL.vx) * WB_WALL; }
    else if (WBALL.x > PEN.x1) { WBALL.x = PEN.x1; WBALL.vx = -Math.abs(WBALL.vx) * WB_WALL; }
    if (WBALL.y < PEN.y0) { WBALL.y = PEN.y0; WBALL.vy = Math.abs(WBALL.vy) * WB_WALL; }
    else if (WBALL.y > PEN.y1) { WBALL.y = PEN.y1; WBALL.vy = -Math.abs(WBALL.vy) * WB_WALL; }
    // ⚠️ ANTI-DEATH, BUT ONLY AT THE EDGES. A ball parked in a corner is a
    // dead toy, so the bay's set walks it back out — but this used to run
    // wherever the ball stopped, which meant a ball at rest in open water was
    // never actually at rest: it crept toward the middle forever. That drift
    // was half of what Trym was seeing as "it slides around too much". Now it
    // only engages within reach of a wall, and gently.
    const spd = Math.hypot(WBALL.vx, WBALL.vy);
    const cornered = WBALL.x - PEN.x0 < 70 || PEN.x1 - WBALL.x < 70
      || WBALL.y - PEN.y0 < 34 || PEN.y1 - WBALL.y < 34;
    if (spd < 10 && cornered) {
      WBALL.vx += ((SWIM.x0 + SWIM.x1) / 2 - WBALL.x) * 0.05 * dt;
      WBALL.vy += ((PEN.y0 + PEN.y1) / 2 - WBALL.y) * 0.14 * dt;
    } else if (spd < 3) {
      WBALL.vx = 0; WBALL.vy = 0;             // properly still
    }
    wballEl.style.left = pct(WBALL.x, W);
    wballEl.style.top = pct(WBALL.y - WBALL.z, H);
    depth(wballEl, WBALL.y);          // sorts by where it FLOATS, not its apex
    // the dip in the water under it: shrinks and fades as the ball rises, which
    // is the whole reason the hop reads as height rather than as the ball just
    // moving up the screen.
    if (wballSh) {
      const k = Math.max(0, 1 - WBALL.z / 150);
      wballSh.style.left = pct(WBALL.x, W);
      wballSh.style.top = pct(WBALL.y, H);
      wballSh.style.opacity = (0.32 * k).toFixed(2);
      wballSh.style.transform = 'translate(-50%,-50%) scale(' + (0.55 + 0.45 * k).toFixed(2) + ')';
      depth(wballSh, WBALL.y - 1);
    }
  }

