// ---- 🐚 the collection contract -------------------------------------------
// Species, names, tiers and atlas indices all come from shell-data.js, which
// tools/build-shell-atlas.py generates from the purchased ShoreThings pack.
// (These used to be 29 shapes GENERATED BY FORMULA here — a swirl equation and
// an ellipse — which is exactly why they read as blobs. Real species now.)
const SHELL_IDS = SHELLS.map((s) => s.id);
const SHELL_BY = {};
SHELLS.forEach((s) => { SHELL_BY[s.id] = s; });
const shellName = (id) => (SHELL_BY[id] ? SHELL_BY[id].name : id);
const shellTier = (id) => SHELL_TIERS[(SHELL_BY[id] || SHELLS[0]).tier];
const shellTile = (i) => (i / (SHELL_TILES - 1) * 100) + '% 0';
// weighted draw — the tier IS the rarity, so a Nautilus really is a find
const SHELL_TOTAL_W = SHELLS.reduce((a, s) => a + SHELL_TIERS[s.tier].w, 0);
function shellForRoll(r) {
  let acc = 0;
  const t = r * SHELL_TOTAL_W;
  for (const s of SHELLS) { acc += SHELL_TIERS[s.tier].w; if (t <= acc) return s.id; }
  return SHELLS[0].id;
}

