const WX_HEAVY_TO = 50;            // heavy rain pulls health toward 50%
const WX_STORM_TO = 8;             // a storm flattens it to ~5-10%
const WX_ROT_SHARE = 0.5;          // …and ruins HALF the planted beds + pots
