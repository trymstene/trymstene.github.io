// ⚠️ BIRDHOUSES ARE DESTROYED, and that is CLAIM RECYCLING rather than damage
// (⭐ Trym's reasoning): posts are first-come with one name each, so permanent
// houses would lock everyone who arrives later out of the feature forever. The
// storm frees the posts. Consistent with border flowers fading at 7 days — the
// park's rule is that nothing is forever, and birdhouses were the exception.
function stormWreck(slots, bd, wd, tr, lv, hs, at) {
  // 50% of PLANTED beds, chosen at random across the whole garden (Trym:
  // "randomized plants across plant boxes", not a contiguous swathe)
  const live = [];
  slots.forEach((s2, i) => { if (s2 && !s2.rot) live.push(i); });
  for (let i = live.length - 1; i > 0; i--) {          // Fisher-Yates
    const j = Math.floor(Math.random() * (i + 1));
    [live[i], live[j]] = [live[j], live[i]];
  }
  live.slice(0, Math.round(live.length * WX_ROT_SHARE)).forEach((i) => { slots[i].rot = at; });
  // the roadside pots take the same share
  const pots = bd.list.filter((f) => !f.rot);
  for (let i = pots.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [pots[i], pots[j]] = [pots[j], pots[i]];
  }
  pots.slice(0, Math.round(pots.length * WX_ROT_SHARE)).forEach((f) => { f.rot = at; });
  // …and the mess it leaves behind, on free grid points
  const taken = new Set([...wd.list, ...tr.list, ...lv.list].map((t) => t.x + ',' + t.y));
  const drop = (list, n, extra) => {
    for (let k = 0; k < n; k++) {
      for (let t = 0; t < 12; t++) {
        const g = WEED_GRID[Math.floor(Math.random() * WEED_GRID.length)];
        const key = g[0] + ',' + g[1];
        if (taken.has(key)) continue;
        taken.add(key);
        list.push({ id: crypto.randomUUID().slice(0, 8), x: g[0], y: g[1], bornAt: at, ...extra });
        break;
      }
    }
  };
  drop(wd.list, 6 + Math.floor(Math.random() * 5));
  drop(tr.list, 3 + Math.floor(Math.random() * 3), { v: 1 + Math.floor(Math.random() * 3) });
  drop(lv.list, 2 + Math.floor(Math.random() * 3));
  hs.list.length = 0;                                   // every birdhouse down
}

// 🧹 THE TIDINESS CEILING (Trym, 30 Jul: "the park has been on 100% the whole
// day … but theres algae in the pond and some weed, and garbage here and
// there … it at least should be reduced some percent"). The drags were always
// in the decay — but they are a RATE, and a watered 64-slot garden out-feeds
// them, so the meter pins at 100 and mess stops registering the moment the
// park is healthy. Raising the drags cannot fix that: a big enough feed still
// wins and still pins. A ceiling is the honest shape — however hard you water,
// THE PARK CANNOT READ PERFECT WHILE THERE IS LITTER IN IT.
// Deliberately small and capped: this is a nudge to tidy up, not a second
// decay. At the ≥80 band the caps are 20 weeds / 6 algae / 4 litter, so a
// fully messy healthy park reads ~90 and a spotless one still reads 100 —
// which is what keeps clearing it worth doing.
// ⚠️ NO CAP, and that is the point: a cap means the first items you clear pay
// NOTHING (you are still pinned to the cap), which is the same dead feedback
// this whole change is fixing. Uncapped and small, every single item you clear
// moves the bar. The ≥80 band's caps are 20 weeds / 6 algae / 4 litter, so the
// worst a spotlessly-fed park can read is ~87 — comfortably above the 80 band
// border, so tidiness alone can never push the park into a worse spawn band.
const TIDY_WEED = 0.3, TIDY_ALGAE = 0.6, TIDY_LITTER = 0.8;
const tidyCeil = (weeds, algae, litter) => 100
  - (TIDY_WEED * weeds.length + TIDY_ALGAE * algae.length + TIDY_LITTER * litter.length);

// 🌿 WEEDS 2.0 + 🌸 THE BLOOM — the park's entropy loop. Weeds are an
// ORGANISM on WEED_GRID (park-weed-grid.js, generated): children sprout NEAR
// a living parent (patches that visibly spread), ~15% of spawns POLLINATE to
// a random far grid point (crossing roads → new patches), and an empty map
// always re-seeds one. Cadence + cap ride the bloom DOWN (bands in garden())
// so a dead park looks OVERRUN — a viewport on a patch reads fully overtaken
// (~30-40 weeds in view) while the global count stays bounded.
// Napkin equilibria (31 Jul retune, one notch harder for the 64-slot era:
// 0.3/h base + 0.035/h/weed vs the saturating feed ≤1.1/h; pull +0.4,
// water +2, plant +6):
//   ≥80: cap 20 → sink ≤1.0/h vs feed max 1.1 — holding at FULL weed cap
//   would take ~180 watered stars, so weeding stays mandatory; weeded +
//   ~18 watered stars (0.55 vs 0.3) holds comfortably
//   60-79: cap 26 → ≤1.21/h ≈ 29/day — a couple of visitors' rounds cover it
//   40-59: cap 40 → ≤1.70/h ≈ 41/day
//   <40: cap 80 → ≤3.10/h ≈ 74/day — the overrun LOOK, but pulling the lot
//   pays +32 bloom and kills the drag; the floor keeps it never-hopeless
const WEED_NEAR = 110;             // a child sprouts this close to its parent
const WEED_POLLINATE = 0.15;       // share of spawns that jump far instead
const BLOOM_FLOOR = 5;             // launch-era floor (was 15) — properly dead, never hopeless
