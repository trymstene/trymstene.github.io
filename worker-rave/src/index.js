      border: bd.list.map((f) => ({ spot: f.spot, kind: f.kind, name: f.name, at: f.at,
        ...(f.rot ? { rot: f.rot } : {}) })),
      algae: alg.list.map((a2) => ({ id: a2.id, x: a2.x, y: a2.y })),
      leaves: lv.list.map((l2) => ({ id: l2.id, x: l2.x, y: l2.y })),
