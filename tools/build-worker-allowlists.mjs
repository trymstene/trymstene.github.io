// GENERATE worker-rave's outfit id allowlists from the single-source manifest
// (src/data/wearables.js) — the worker bundle can't import site source, and
// the hand-pasted mirror kept threatening to drift. Now the manifest is law.
//
//   node tools/build-worker-allowlists.mjs
//
// Rewrites the block between ALLOWLISTS-START/END in worker-rave/src/index.js,
// then you deploy the worker. Part of the NEW-WEARABLE checklist.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { WEARABLE_PACKS } from '../src/data/wearables.js';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const packs = Object.values(WEARABLE_PACKS);

// member: (supporter) gear is excluded like raveOnly — revocable gear must
// never enter the client-claimable allowlists, or any raver could broadcast
// it. When server-side grant verification lands, member ids get admitted
// per-connection (the beer pattern), not here.
const hats = ['none', ...packs.flatMap((p) => p.hats || []).filter((d) => !d.member).map((d) => d.id)];
const shades = ['none', ...packs.flatMap((p) => p.shades || []).filter((d) => !d.member).map((d) => d.id)];
// raveOnly items (beer/cone/vinyl/broom) are server-granted — excluded so
// sanitize strips them from client outfits
const extras = packs.flatMap((p) => p.extras || []).filter((d) => !d.raveOnly && !d.member).map((d) => d.id);
const drops = packs.flatMap((p) => [...(p.hats || []), ...(p.shades || []), ...(p.extras || [])])
  .filter((d) => d.drop).map((d) => d.id);

const q = (a) => '[' + a.map((s) => `'${s}'`).join(', ') + ']';
const block = [
  '// ALLOWLISTS-START — GENERATED by tools/build-worker-allowlists.mjs from',
  '// src/data/wearables.js (the single-source manifest). NEVER edit by hand:',
  '// rerun the script after any wearable change, then deploy this worker.',
  '// raveOnly items (beer/cone/vinyl/broom) are server-granted and excluded',
  '// so sanitize strips them from client outfits.',
  `const HAT_IDS = ${q(hats)};`,
  `const DROP_IDS = ${q(drops)};`,
  `const SHADE_IDS = ${q(shades)};`,
  `const EXTRA_IDS = ${q(extras)};`,
  '// ALLOWLISTS-END',
].join('\n');

// 🎩 THE STAND PRICES (slice 4, 2 Sep 2026): a Banana Stand wearable is
// yours only when worker-pass accepted the spend that names it, and the
// worker judges the spend against the MANIFEST price — projected here, never
// hand-mirrored. The client pass lib gets the id class only (it must stay
// manifest-free). ⚠️ DEPLOY ORDER for a price change: a RAISE ships the site
// first, then the worker; a CUT ships the worker first. A NEW stand item =
// regen + deploy worker-pass BEFORE the site (an unknown id is a plain spend:
// the player would pay and own nothing).
const stand = packs.flatMap((p) => [...(p.hats || []), ...(p.shades || []), ...(p.extras || [])])
  .filter((d) => d.preview === 'stand' && d.price > 0 && !d.member);
const priceBlock = [
  '// OWN-PRICES-START — GENERATED by tools/build-worker-allowlists.mjs from',
  '// src/data/wearables.js (preview: stand + price). NEVER edit by hand.',
  `const OWN_PRICES = { ${stand.map((d) => `${d.id}: ${d.price}`).join(', ')} };`,
  '// OWN-PRICES-END',
].join('\n');
const idsBlock = [
  '// OWN-IDS-START — GENERATED by tools/build-worker-allowlists.mjs (the stand ids',
  '// whose ownership the pass worker authors). NEVER edit by hand.',
  `const OWN_IDS = ${q(stand.map((d) => d.id))};`,
  '// OWN-IDS-END',
].join('\n');

const CHECK = process.argv.includes('--check');
const targets = [
  [join(root, 'worker-rave', 'src', 'index.js'), /\/\/ ALLOWLISTS-START[\s\S]*?\/\/ ALLOWLISTS-END/, block, 'ALLOWLISTS', 'worker allowlists UPDATED (deploy worker-rave)'],
  [join(root, 'worker-pass', 'src', 'index.js'), /\/\/ OWN-PRICES-START[\s\S]*?\/\/ OWN-PRICES-END/, priceBlock, 'OWN-PRICES', 'worker-pass OWN_PRICES UPDATED (deploy worker-pass)'],
  [join(root, 'src', 'lib', 'banana-pass.js'), /\/\/ OWN-IDS-START[\s\S]*?\/\/ OWN-IDS-END/, idsBlock, 'OWN-IDS', 'banana-pass OWN_IDS UPDATED'],
];
let stale = 0;
for (const [path, re, blk, name, note] of targets) {
  const src = readFileSync(path, 'utf8');
  if (!re.test(src)) { console.error(`${name} markers not found in ${path}`); process.exit(1); }
  const next = src.replace(re, blk);
  const changed = next !== src;
  if (changed) stale++;
  if (!CHECK) writeFileSync(path, next);
  console.log(`${name}: ${changed ? (CHECK ? 'STALE' : note) : 'in sync'}`);
}
console.log(`hats ${hats.length} · drops ${drops.length} · shades ${shades.length} · extras ${extras.length} · stand ${stand.length}`);
if (CHECK && stale) { console.error('generated blocks are stale — run node tools/build-worker-allowlists.mjs and commit'); process.exit(1); }
